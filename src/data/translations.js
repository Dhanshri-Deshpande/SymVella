/**
 * Universal translate helper with dot notation and parameter substitution
 * e.g., translate("hi", "home.day_count", { day: 21, total: 32 })
 */
export function translate(lang = "en", path = "", params = {}) {
  const currentLangTable = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const keys = path.split(".");
  
  let val = currentLangTable;
  for (const k of keys) {
    if (val && typeof val === "object" && k in val) {
      val = val[k];
    } else {
      val = null;
      break;
    }
  }

  // Fallback to English if translation missing in selected language
  if (val === undefined || val === null) {
    let engVal = TRANSLATIONS.en;
    for (const ek of keys) {
      if (engVal && typeof engVal === "object" && ek in engVal) {
        engVal = engVal[ek];
      } else {
        engVal = null;
        break;
      }
    }
    val = engVal ?? (typeof params === "string" ? params : path);
  }

  if (typeof val !== "string") return val;

  // Replace tokens like {day}, {time}, {total} if params is an object
  if (params && typeof params === "object") {
    Object.keys(params).forEach(param => {
      val = val.replace(new RegExp(`\\{${param}\\}`, "g"), params[param]);
    });
  }

  return val;
}
